"""Emit the general-capability table from the evaluation summaries themselves.

Reads only what the scoring jobs wrote. A metric that was not produced stays an
em-dash: a missing evaluation is never rendered as a zero, and no cell is typed
by hand. Response length is carried alongside the scores because a shorter
answer moves every other column at once.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

# (column header, benchmark file stem, path inside that summary)
COLUMNS = (
    ("IFEval strict", "ifeval", ("metrics", "strict_prompt_accuracy", "estimate")),
    ("\\textsc{GSM8K} EM", "gsm8k", ("metrics", "exact_match", "estimate")),
    ("HarmBench $\\downarrow$", "harmbench", ("metrics", "overall", "estimate")),
    ("Alpaca ref.\\ win", "alpaca_eval", ("subsets", "all805", "estimate")),
    ("Arena ref.\\ win", "arena_hard", ("subsets", "hard500", "estimate")),
)
LENGTH = ("alpaca_eval", ("subsets", "all805", "candidate_diagnostics", "median_response_tokens"))


def find(root: Path, bench: str, label: str):
    matches = sorted(root.glob(f"evaluations/*/{bench}_{label}.summary.json"))
    if not matches:
        return None
    if len(matches) > 1:
        raise ValueError(f"{bench}/{label} scored in more than one place: {matches}")
    return json.loads(matches[0].read_text())


def dig(payload, path):
    for key in path:
        if payload is None:
            return None
        payload = payload.get(key)
    return payload


def collect(root: Path, labels):
    table = {}
    for label in labels:
        row = {}
        for header, bench, path in COLUMNS:
            row[header] = dig(find(root, bench, label), path)
        row["med.\\ tokens"] = dig(find(root, LENGTH[0], label), LENGTH[1])
        gsm = find(root, "gsm8k", label)
        row["_gsm8k_parse_failure"] = dig(gsm, ("metrics", "parse_failure_rate", "estimate"))
        table[label] = row
    return table


def cell(value):
    if value is None:
        return "---"
    return f"${value:.0f}$" if value >= 10 else f"${value:.3f}$"


def render(table, display):
    headers = [header for header, _, _ in COLUMNS] + ["med.\\ tokens"]
    lines = [
        "% generated by scripts/experiments/nbpo_repair_20260909/export_capability_table.py",
        "\\begin{tabular}{l" + "r" * len(headers) + "}", "\\toprule",
        "method & " + " & ".join(headers) + "\\\\", "\\midrule",
    ]
    for label, row in table.items():
        lines.append(display.get(label, label) + " & "
                     + " & ".join(cell(row[header]) for header in headers) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/work/nbpo_repair_20260909"))
    ap.add_argument("--label", action="append", required=True, metavar="NAME=DISPLAY")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--json-out", type=Path)
    args = ap.parse_args()
    display = dict(spec.split("=", 1) for spec in args.label)
    table = collect(args.root, list(display))
    args.out.write_text(render(table, display))
    if args.json_out:
        args.json_out.write_text(json.dumps(table, indent=2) + "\n")
    missing = {label: [k for k, v in row.items() if v is None and not k.startswith("_")]
               for label, row in table.items()}
    print(json.dumps({"table": table, "missing": {k: v for k, v in missing.items() if v}}, indent=2))


if __name__ == "__main__":
    main()
