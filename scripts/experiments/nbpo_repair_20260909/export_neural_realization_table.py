"""Emit the held-out neural-realization table from the arms' own trainer states.

Nothing here is typed by hand: every number comes out of a trainer_state.json
written by the run that produced it, so the table cannot drift from the arm.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

FIELDS = ("eval_nbpo/nmse", "eval_nbpo/sign_accuracy", "eval_nbpo/pearson",
          "eval_nbpo/spearman", "eval_nbpo/mean_logratio",
          "eval_nbpo/target_second_moment", "eval_nbpo/h_second_moment",
          "eval_nbpo/target_h_cross_moment")


def trajectory(state_path: Path):
    state = json.loads(state_path.read_text())
    rows = []
    for entry in state["log_history"]:
        if "eval_nbpo/nmse" not in entry:
            continue
        row = {"step": int(entry["step"]), **{f: entry.get(f) for f in FIELDS}}
        # Split the residual into what the direction explains and what the
        # magnitude costs. nMSE at the best single rescaling of h is
        # 1 - E[hT]^2 / (E[h^2] E[T^2]); the gap to the reported nMSE is
        # entirely scale. Both come from the moments the run already logged.
        second, cross = row["eval_nbpo/h_second_moment"], row["eval_nbpo/target_h_cross_moment"]
        target = row["eval_nbpo/target_second_moment"]
        if second and target:
            row["shape_r2"] = cross * cross / (second * target)
            row["nmse_best_scale"] = 1.0 - row["shape_r2"]
            row["best_scale"] = cross / second
        else:
            row["shape_r2"] = row["nmse_best_scale"] = row["best_scale"] = None
        rows.append(row)
    return rows


def cell(value, digits=3):
    return "---" if value is None else f"{value:.{digits}f}"


def render(arms, final_only=False):
    """Only the tabular: the caption lives in the manuscript, as elsewhere here.

    ``final_only`` keeps one row per arm, at that arm's own declared horizon --
    the compact form for the body, with the full trajectories in the appendix.
    """
    lines = [
        r"% generated by scripts/experiments/nbpo_repair_20260909/export_neural_realization_table.py",
        r"\begin{tabular}{lrrrrrrr}", r"\toprule",
        r"Projection & Updates & nMSE & nMSE$^\ast$ & Sign acc. & Pearson & Spearman & $\overline{\log(\pi_\theta/\pi_t)}$\\",
        r"\midrule",
    ]
    for position, (name, rows) in enumerate(arms.items()):
        if position and not final_only:
            lines.append(r"\midrule")
        if final_only:
            rows = rows[-1:]
        for index, row in enumerate(rows):
            label = name if index == 0 or final_only else ""
            lines.append(
                f"{label} & {row['step']} & {cell(row['eval_nbpo/nmse'])} & "
                f"{cell(row['nmse_best_scale'])} & "
                f"{cell(row['eval_nbpo/sign_accuracy'])} & {cell(row['eval_nbpo/pearson'])} & "
                f"{cell(row['eval_nbpo/spearman'])} & {cell(row['eval_nbpo/mean_logratio'], 2)}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", action="append", required=True,
                    metavar="NAME=PATH", help="display name = trainer_state.json path")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--final-only", action="store_true")
    args = ap.parse_args()
    arms = {}
    for spec in args.arm:
        name, _, path = spec.partition("=")
        arms[name] = trajectory(Path(path))
        if not arms[name]:
            raise ValueError(f"No held-out evaluations recorded in {path}")
    args.out.write_text(render(arms, args.final_only))
    print(json.dumps({name: rows for name, rows in arms.items()}, indent=2))


if __name__ == "__main__":
    main()
