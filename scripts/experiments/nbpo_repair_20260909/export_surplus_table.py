"""Emit the SafeRLHF bargaining table from the evaluation reports themselves.

Reports the objective-wise surplus over the reference and the worst objective,
which is the quantity the bargaining objective is about, with the paired
prompt-bootstrap intervals the evaluation already computed. The worst objective
is min_k E_x[s_k] -- the minimum of the per-objective means, never the mean of
the per-prompt minima, which is a different and always smaller number.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

BLOCK = "paired_greedy_base_comparison"


def report(root: Path, label: str):
    path = root / f"evaluations/saferlhf_{label}_v1/{label}/report.json"
    if not path.exists():
        matches = sorted(root.glob(f"evaluations/*/{label}/report.json"))
        if not matches:
            return None
        path = matches[0]
    return json.loads(path.read_text())


def cell(value, digits=4):
    return "---" if value is None else f"${value:+.{digits}f}$"


def interval(entry, index):
    if entry is None:
        return None, None
    low, high = entry["ci95"][index]
    return entry["estimate"][index], (low, high)


def collect(root: Path, labels, split):
    out = {}
    for label in labels:
        payload = report(root, label)
        if payload is None:
            out[label] = None
            continue
        metrics = payload["splits"][split][BLOCK]["metrics"]
        objectives = payload["objectives"]
        surplus = metrics.get("s_original_reference")
        delta = metrics.get("delta_vs_base_greedy")
        row = {"objectives": objectives, "surplus": {}, "delta_vs_base": {}}
        for index, objective in enumerate(objectives):
            estimate, bounds = interval(surplus, index)
            row["surplus"][objective] = {"estimate": estimate, "ci95": bounds}
            estimate, bounds = interval(delta, index)
            row["delta_vs_base"][objective] = {"estimate": estimate, "ci95": bounds}
        values = [row["surplus"][o]["estimate"] for o in objectives]
        row["worst_objective"] = min(values) if all(v is not None for v in values) else None
        row["worst_objective_definition"] = "min_k E_x[s_k], not E_x[min_k s_k]"
        row["n_prompts"] = payload["splits"][split]["n_prompts"] if "n_prompts" in payload["splits"][split] else payload["splits"][split].get("n_scored")
        row["response_length"] = payload.get("response_length")
        row["teacher_truncation"] = payload.get("teacher_truncation")
        out[label] = row
    return out


def render(table, display, objectives):
    headers = [f"$s_{{\\mathrm{{{o[:4]}}}}}$" for o in objectives] + [r"$\min_k s_k$", "med.\\ tok."]
    lines = ["% generated by scripts/experiments/nbpo_repair_20260909/export_surplus_table.py",
             "\\begin{tabular}{l" + "r" * len(headers) + "}", "\\toprule",
             "method & " + " & ".join(headers) + "\\\\", "\\midrule"]
    for label, row in table.items():
        name = display.get(label, label)
        if row is None:
            lines.append(name + " & " + " & ".join(["---"] * len(headers)) + "\\\\")
            continue
        cells = [cell(row["surplus"][o]["estimate"]) for o in objectives]
        cells.append(cell(row["worst_objective"]))
        length = (row.get("response_length") or {}).get("median_tokens")
        cells.append("---" if length is None else f"${length:.0f}$")
        lines.append(name + " & " + " & ".join(cells) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("/work/nbpo_repair_20260909"))
    ap.add_argument("--label", action="append", required=True, metavar="NAME=DISPLAY")
    ap.add_argument("--split", default="dev", choices=("dev", "test"))
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--json-out", type=Path)
    args = ap.parse_args()
    display = dict(spec.split("=", 1) for spec in args.label)
    table = collect(args.root, list(display), args.split)
    present = next((row for row in table.values() if row), None)
    if present is None:
        raise ValueError("No SafeRLHF report found for any requested label")
    args.out.write_text(render(table, display, present["objectives"]))
    if args.json_out:
        args.json_out.write_text(json.dumps({"split": args.split, "table": table}, indent=2) + "\n")
    print(json.dumps({"split": args.split, "table": table}, indent=2))


if __name__ == "__main__":
    main()
