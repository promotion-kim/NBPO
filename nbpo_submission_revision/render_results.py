#!/usr/bin/env python3
"""Render only declared numeric cells; raw artifact references are mandatory."""
from pathlib import Path
import json, math, re
ROOT=Path(__file__).resolve().parent
j=json.loads((ROOT/'templates/results.json').read_text())
keys=json.loads((ROOT/'templates/result_keys.json').read_text())
assert set(j['cells']) == set(keys), 'Do not add, remove or rename table cells'
lines=[r'% Generated by render_results.py; edit templates/results.json only.']
for key in keys:
    rec=j['cells'][key]
    if rec is None: value=r'\pending'
    else:
        assert j['contract_id'] != 'UNMEASURED', 'Set frozen contract ID'
        assert isinstance(rec,dict) and rec.get('artifact') and re.fullmatch(r'[0-9a-f]{64}',rec.get('sha256','')), key
        v=rec['value']; assert isinstance(v,(int,float)) and not isinstance(v,bool) and math.isfinite(v), key
        if key.endswith(('N','S')): assert v>=0 and int(v)==v; value=str(int(v))
        else:
            if key.endswith(('C','D','TV','Wone','Wtwo','Min')): assert 0<=v<=1, key
            value=f'{v:.4f}'
        if 'ci95' in rec:
            lo,hi=rec['ci95']; assert all(math.isfinite(x) for x in (lo,hi)) and lo<=hi, key
        value='$'+value+'$'
    lines.append(r'\expandafter\def\csname nbporesult@'+key+r'\endcsname{'+value+'}')
(ROOT/'templates/results_auto.tex').write_text('\n'.join(lines)+'\n')
print('Rendered',len(keys),'cells;',sum(j['cells'][k] is not None for k in keys),'measured. Artifact hashes are provenance declarations; verify source bytes separately.')
