#!/usr/bin/env python3
"""Generate the Qwen3-8B evaluator-power diagnostic table from measured JSON."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


LABELS = {"skywork": "Skywork Reward V2", "athene": "Athene-RM-8B"}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--sealed-per-objective", type=Path)
    parser.add_argument("--sealed-summary", type=Path)
    parser.add_argument("--macros-output", type=Path)
    args = parser.parse_args()
    payload = json.loads(args.summary.read_text())
    if payload.get("status") != "completed" or payload.get("num_prompts") != 604:
        raise RuntimeError("power diagnostic is incomplete")
    results = payload["reward_models"]
    if set(results) != set(LABELS):
        raise RuntimeError("unexpected reward-model set")
    lines = [
        "% AUTO-GENERATED by build_qwen3_power_diagnostic_table.py; do not hand-edit numbers",
        "\\begin{table}[t]", "\\centering", "\\scriptsize",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\begin{tabular}{lrrr}", "\\toprule",
        "Evaluator & Raw mean spread & vs. base & Pairs / 45 \\\\",
        "\\midrule",
    ]
    for name in ("skywork", "athene"):
        result = results[name]
        lines.append(
            f"{LABELS[name]} & {float(result['model_mean_spread']):.4f} & "
            f"{int(result['detectable_trained_models_vs_base'])} & "
            f"{int(result['detectable_pairwise_differences'])} \\\\"
        )
    lines.extend([
        "\\bottomrule", "\\end{tabular}",
        "\\caption{\\textbf{Pre-committed evaluator-power diagnostic} on the preserved 604-prompt sealed generations. Raw mean spread is the maximum minus minimum model mean within each evaluator and is not comparable across evaluator scales. The last two columns count paired 95\\% bootstrap intervals that exclude zero. Skywork separates no pair; Athene separates three of 45 pairs under unadjusted intervals, but neither evaluator separates a trained model from base.}",
        "\\label{tab:qwen3-power-diagnostic}", "\\end{table}", "",
    ])
    args.output.write_text("\n".join(lines), encoding="utf-8")

    macro_args = (args.sealed_per_objective, args.sealed_summary, args.macros_output)
    if any(value is not None for value in macro_args):
        if not all(value is not None for value in macro_args):
            raise RuntimeError("all sealed macro inputs must be provided together")
        with args.sealed_per_objective.open(newline="", encoding="utf-8") as handle:
            per_objective = list(csv.DictReader(handle))
        by_objective = {}
        for row in per_objective:
            by_objective.setdefault(row["objective"], []).append(float(row["mean_raw_score"]))
        expected_objectives = {"helpfulness", "safety", "conciseness"}
        if set(by_objective) != expected_objectives:
            raise RuntimeError("unexpected sealed objective set")
        raw_spreads = {
            name: max(values) - min(values) for name, values in by_objective.items()
        }
        sealed = json.loads(args.sealed_summary.read_text())
        ranked = sealed.get("ranked", [])
        if sealed.get("p1_sealed_test_opened") is not True or not ranked:
            raise RuntimeError("sealed summary is incomplete")
        worst = [float(row["mean_primary_prompt_worst_norm_score"]) for row in ranked]
        macro_lines = [
            "% AUTO-GENERATED by build_qwen3_power_diagnostic_table.py; do not hand-edit numbers",
            f"\\newcommand{{\\QwenSealedPromptCount}}{{{int(payload['num_prompts'])}}}",
            f"\\newcommand{{\\QwenBootstrapResamples}}{{{int(sealed['bootstrap_resamples']):,}}}",
            f"\\newcommand{{\\QwenBootstrapSeed}}{{{int(sealed['bootstrap_seed'])}}}",
            f"\\newcommand{{\\QwenArmoHelpSpread}}{{{raw_spreads['helpfulness']:.4f}}}",
            f"\\newcommand{{\\QwenArmoSafetySpread}}{{{raw_spreads['safety']:.4f}}}",
            f"\\newcommand{{\\QwenArmoConcisenessSpread}}{{{raw_spreads['conciseness']:.4f}}}",
            f"\\newcommand{{\\QwenArmoMaxSpread}}{{{max(raw_spreads.values()):.4f}}}",
            f"\\newcommand{{\\QwenWorstNormLow}}{{{min(worst):.3f}}}",
            f"\\newcommand{{\\QwenWorstNormHigh}}{{{max(worst):.3f}}}",
            f"\\newcommand{{\\QwenSkyworkDetectedPairs}}{{{int(results['skywork']['detectable_pairwise_differences'])}}}",
            f"\\newcommand{{\\QwenAtheneDetectedPairs}}{{{int(results['athene']['detectable_pairwise_differences'])}}}",
            f"\\newcommand{{\\QwenPowerPairTotal}}{{{int(results['athene']['total_pairwise_differences'])}}}",
            "",
        ]
        args.macros_output.write_text("\n".join(macro_lines), encoding="utf-8")


if __name__ == "__main__":
    main()
